  /// Search for content by keywords
  static List<Map<String, String>> search(String query, {String language = 'ar'}) {
    final results = <Map<String, String>>[];
    final queryLower = query.toLowerCase();

    for (final entry in _content.entries) {
      final keywordsStr = entry.value['keywords'] ?? '';
      final keywords = keywordsStr.split(',').map((s) => s.trim()).toList();
      final title = language == 'ar' ? entry.value['titleAr'] : entry.value['titleEn'];
      final body = language == 'ar' ? entry.value['bodyAr'] : entry.value['bodyEn'];

      // Check if query matches any keyword
      final matchesKeyword = keywords.any((kw) => queryLower.contains(kw.toLowerCase()));

      // Check if query matches title
      final matchesTitle = title?.toLowerCase().contains(queryLower) ?? false;

      if (matchesKeyword || matchesTitle) {
        results.add({
          'id': entry.key,
          'title': title ?? '',
          'body': body ?? '',
          'category': entry.value['category'] ?? '',
        });
      }
    }

    return results;
  }

